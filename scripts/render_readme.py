"""Render the README Key Results block from the files in results/.

    python scripts/render_readme.py          # rewrite the block in README.md
    python scripts/render_readme.py --check  # exit 1 if README.md is out of date

Every number between the results markers in README.md comes from this script,
so a README number can never drift away from the notebook output.
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
START = "<!-- results:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- results:end -->"
ALPHA = 0.01


def pct(x, d=2):
    return f"{x * 100:.{d}f}%"


def render() -> str:
    head = json.loads((RES / "headline.json").read_text())
    bt = pd.read_csv(RES / "backtest_summary.csv", index_col="model")
    st = pd.read_csv(RES / "stress_violation_rates.csv")
    es = pd.read_csv(RES / "es_test.csv", index_col="model")
    cv = pd.read_csv(RES / "component_var.csv", index_col="asset")

    out = []
    out.append(
        f"### Full-Sample Backtest ({head['backtest_days']:,} days, "
        f"{head['sample_start']} to {head['sample_end']}, expected violations: "
        f"{head['expected_violations']:.1f})"
    )
    out.append("")
    out.append("| Model | Violations | Rate | p_POF | p_IND | p_CC |")
    out.append("|-------|-----------|------|-------|-------|------|")
    bt = bt.sort_values(["p_CC", "p_POF"], ascending=False)
    for m, r in bt.iterrows():
        out.append(
            f"| {m} | {int(r.Violations)} | {pct(r.ViolRate)} | {r.p_POF:.3f} | {r.p_IND:.3f} | {r.p_CC:.3f} |"
        )
    out.append("")
    n_cc = int((bt.p_CC > 0.05).sum())
    n_ind = int((bt.p_IND <= 0.05).sum())
    out.append(
        f"{n_cc} of {len(bt)} models pass the Christoffersen conditional coverage test at 5%. "
        f"{n_ind} of {len(bt)} reject independence of violations at 5%."
    )
    es_parts = []
    for m, r in es.iterrows():
        verdict = "rejected" if r.p_val <= 0.05 else "not rejected"
        es_parts.append(f"{m} {verdict} (t = {r.t_stat:.2f}, p = {r.p_val:.3f})")
    out.append(f"McNeil-Frey ES test: {'; '.join(es_parts)}. A positive t-statistic means the model understates tail losses.")
    out.append("")

    out.append("### Sub-Period Violation Rates (target 1.00%)")
    out.append("")
    models = ["GJR-GARCH-t", "APARCH-EVT", "FHS-EVT", "HS"]
    models = [m for m in models if m in set(st.model)]
    out.append("| Period | Days | " + " | ".join(models) + " |")
    out.append("|---|---|" + "---|" * len(models))
    for period, g in st.groupby("period", sort=False):
        g = g.set_index("model")
        cells = []
        for m in models:
            vr = g.loc[m, "viol_rate"]
            flag = "✗" if abs(vr - ALPHA) / ALPHA > 0.5 else "✓"
            cells.append(f"{pct(vr)} {flag}")
        out.append(f"| {period} | {int(g['days'].iloc[0])} | " + " | ".join(cells) + " |")
    out.append("")
    out.append("✗ marks a violation rate more than 50% away from the 1% target, the same rule the notebook uses.")
    out.append("")

    out.append("### Component VaR, Normal vs. Stress Covariance")
    out.append("")
    widen = head["portfolio_var_gfc"] / head["portfolio_var_normal"] - 1
    out.append(
        f"Portfolio 99% VaR ({head['component_var_model']} critical value): **{pct(head['portfolio_var_normal'])}** "
        f"with full-sample covariance, **{pct(head['portfolio_var_gfc'])}** with GFC covariance "
        f"({head['gfc_window'][0]} to {head['gfc_window'][1]}), a widening of {widen * 100:.0f}%."
    )
    out.append("")
    out.append("| Asset | Weight | CompVaR share (normal) | CompVaR share (GFC) | Change |")
    out.append("|---|---|---|---|---|")
    for a, r in cv.iterrows():
        d = (r.compvar_share_gfc - r.compvar_share_normal) * 100
        out.append(
            f"| {a} | {r.weight * 100:.0f}% | {pct(r.compvar_share_normal)} | {pct(r.compvar_share_gfc)} | {d:+.1f}pp |"
        )
    return "\n".join(out)


def main():
    readme = ROOT / "README.md"
    text = readme.read_text()
    if START not in text or END not in text:
        sys.exit("README.md has no results markers")
    pre, rest = text.split(START, 1)
    _, post = rest.split(END, 1)
    new = pre + START + "\n" + render() + "\n" + END + post
    if "--check" in sys.argv:
        if new != text:
            sys.exit("README.md Key Results are out of date. Run: python scripts/render_readme.py")
        print("README.md Key Results match results/")
        return
    readme.write_text(new)
    print("README.md Key Results rendered from results/")


if __name__ == "__main__":
    main()
