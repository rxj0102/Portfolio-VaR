"""Render the README results from results/metrics.json.

    python scripts/render_readme.py          rewrite the generated blocks
    python scripts/render_readme.py --check  exit 1 if the README is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK = "<!-- {name}:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- {name}:end -->"
ORDER = ["HS", "EWMA-N", "GARCH-N", "GARCH-t", "GJR-GARCH-t", "EGARCH-t", "FHS-EWMA", "FHS-GARCH", "FHS-GJR",
         "GJR-EVT"]


def p(x):
    return "<0.001" if x < 0.001 else f"{x:.3f}"


def headline(m: dict) -> str:
    s, mod, short = m["sample"], m["models"], m["in_sample_shortcut"]
    passed = [k for k in ORDER if mod[k]["status"] == "PASS"]
    passed_short = [k for k in short if short[k]["status"] == "PASS"]
    es_reject = [k for k in ORDER if mod[k].get("es_p") is not None and mod[k]["es_p"] < 0.05]
    es_ok = [k for k in ORDER if mod[k].get("es_p") is not None and mod[k]["es_p"] >= 0.05]
    fewer = [k for k in short if short[k]["violations"] < mod[k]["violations"]]
    checks = {
        "exactly one model passes out of sample": len(passed) == 1,
        "more models pass with the in-sample shortcut": len(passed_short) > len(passed),
        "the shortcut never shows more violations": len(fewer) >= len(short) - 1
        and all(short[k]["violations"] <= mod[k]["violations"] for k in short),
        "the Student-t models that fail the ES test all understate it": bool(es_reject)
        and all(mod[k]["es_t"] > 0 and k.endswith("-t") for k in es_reject),
        "every semi-parametric ES passes": all(k in es_ok for k in ("FHS-GARCH", "FHS-GJR", "GJR-EVT")),
        "historical simulation spends time in the red zone": mod["HS"]["zones"]["red"] > 0.01,
        "the Dynamic Quantile test rejects every model": all(mod[k]["p_dq"] < 0.05 for k in ORDER),
        "every ES model is in the FZ0 confidence set": all(mod[k]["in_mcs_fz0"] for k in ORDER if "in_mcs_fz0" in mod[k]),
    }
    failed = [k for k, ok in checks.items() if not ok]
    if failed:
        raise SystemExit("README summary no longer matches the results; rewrite headline() in "
                         "scripts/render_readme.py. Failed: " + "; ".join(failed))
    w = passed[0]
    es_ts = ", ".join(f"{mod[k]['es_t']:.1f}" for k in es_reject)
    return (
        f"**Answer, over {s['n_days']} out-of-sample days from {s['first_day'][:4]} to {s['last_day'][:4]}: "
        f"one of ten, and none under a stricter timing test.** Only {w} passes all three Christoffersen tests "
        f"({mod[w]['violations']} violations against {s['expected_violations']:.0f} expected). The Dynamic Quantile "
        f"test of Engle and Manganelli, which asks whether a violation could be predicted from the last four days and "
        f"the VaR level rather than from yesterday alone, rejects all ten at 5%, {w} included (p = "
        f"{mod[w]['p_dq']:.3f}). Historical simulation, the simplest "
        f"method, has {mod['HS']['violations']} violations and spends "
        f"{mod['HS']['zones']['red']:.0%} of days in the Basel red zone. Models that take the tail from past "
        f"residuals (FHS-GJR, GJR-EVT) get the number of violations right but not their timing: the "
        f"violations still cluster. For expected shortfall the order reverses. "
        f"{', '.join(es_reject)} understate it (t = "
        f"{es_ts}), while the "
        f"residual-based models do not.\n\n"
        f"**The same models fitted once on the whole sample look better than they are.** That shortcut "
        f"passes {len(passed_short)} models instead of {len(passed)} and shows fewer violations for "
        f"{len(fewer)} of {len(short)}: FHS-GARCH drops from {mod['FHS-GARCH']['violations']} to "
        f"{short['FHS-GARCH']['violations']}, because its tail quantile has already seen 2008 and 2020."
    )


def results(m: dict) -> str:
    s, mod, short = m["sample"], m["models"], m["in_sample_shortcut"]
    out = [f"Portfolio returns {s['first_day']} to {s['last_day']} ({s['n_days']} days, {s['expected_violations']:.1f} "
           f"violations expected at 99%). Every model is re-estimated every {s['refit_days']} trading days "
           f"({s['n_refits']} times) on all earlier returns; the first fit uses {s['training_days_first']} days "
           f"from {s['data_first']}. Annual volatility {s['ann_vol']:.1%}, skewness {s['skew']:.2f}, excess "
           f"kurtosis {s['excess_kurtosis']:.1f}.", "",
           "**Out-of-sample backtest, 99% one day VaR**", "",
           "| Model | Violations | Rate | Coverage p | Independence p | Joint p | Verdict | DQ p | In 90% MCS | "
           "Days green / yellow / red |", "|---|---|---|---|---|---|---|---|---|---|"]
    for k in ORDER:
        r = mod[k]
        z = r["zones"]
        out.append(f"| {k} | {r['violations']} | {r['rate']:.2%} | {p(r['p_pof'])} | {p(r['p_ind'])} | "
                   f"{p(r['p_cc'])} | {'**Pass**' if r['status'] == 'PASS' else r['status'].replace('FAIL: ', 'Fails ')} | "
                   f"{p(r['p_dq'])} | {'yes' if r['in_mcs'] else 'no'} | {z['green']:.0%} / {z['yellow']:.0%} / {z['red']:.0%} |")
    out += ["", "Coverage is the Kupiec test, independence and joint are Christoffersen's; a p-value below 0.05 "
            "fails; the verdict uses these three. DQ is the Dynamic Quantile test (Engle and Manganelli 2004): a regression of the hit on a constant, four lagged hits and the VaR forecast, chi-squared with 6 degrees of freedom. MCS is the Model Confidence Set on quantile loss. The zones count exceptions in the "
            "previous 250 days: green up to 4, yellow 5 to 9, red 10 or more.", "",
            "**Expected shortfall** (McNeil-Frey test; positive t means losses beyond VaR were larger than "
            "the model's ES; FZ0 is the joint VaR and ES loss of Patton, Ziegel and Chen, lower is better)", "",
            "| Model | t | p | FZ0 loss | In 90% MCS on FZ0 |", "|---|---|---|---|---|"]
    for k in ORDER:
        if mod[k].get("es_p") is not None:
            out.append(f"| {k} | {mod[k]['es_t']:+.2f} | {p(mod[k]['es_p'])} | {mod[k]['fz0_loss']:.4f} | "
                       f"{'yes' if mod[k]['in_mcs_fz0'] else 'no'} |")
    fz = {k: mod[k]["fz0_loss"] for k in ORDER if "fz0_loss" in mod[k]}
    best = min(fz, key=fz.get)
    out += ["", f"Expected shortfall has no loss function of its own, but VaR and ES together do (Fissler and Ziegel "
            f"2016), so the FZ0 loss ranks the models on both at once. {best} has the lowest, but the Model Confidence "
            f"Set keeps all {len(fz)}: on joint VaR and ES accuracy the data cannot separate them."]
    out += ["", "**The in-sample shortcut**: each model fitted once on the whole sample, then scored on the same "
            "days", "", "| Model | Violations, out of sample | Violations, shortcut | Verdict, out of sample | "
            "Verdict, shortcut |", "|---|---|---|---|---|"]
    for k in short:
        a, b = mod[k], short[k]
        fmt = lambda x: "Pass" if x == "PASS" else x.replace("FAIL: ", "Fails ")  # noqa: E731
        out.append(f"| {k} | {a['violations']} | {b['violations']} | {fmt(a['status'])} | {fmt(b['status'])} |")
    per = m["periods"]
    labs = list(per)
    out += ["", "**Violation rate by period** (target 1.00%)", "",
            "| Model | " + " | ".join(f"{lab} ({per[lab]['days']} d)" for lab in labs) + " |",
            "|---|" + "---|" * len(labs)]
    for k in ORDER:
        out.append(f"| {k} | " + " | ".join(f"{per[lab]['rate'][k]:.2%}" for lab in labs) + " |")
    c = m["component_var"]
    out += ["", f"**Where the risk sits.** Delta-normal 99% VaR is {c['full']['var']:.2%} with the covariance of "
            f"the whole backtest window and {c['stress']['var']:.2%} with the covariance of "
            f"{c['stress_window'][0]} to {c['stress_window'][1]} ({c['stress_days']} days). Shares of that VaR:",
            "", "| Asset | Weight | Share, whole window | Share, 2008 to mid 2009 |", "|---|---|---|---|"]
    for a, wgt in m["weights"].items():
        out.append(f"| {a} | {wgt:.0%} | {c['full']['share'][a]:.0%} | {c['stress']['share'][a]:.0%} |")
    return "\n".join(out)


def fill(text: str, name: str, body: str) -> str:
    start, end = MARK.format(name=name), END.format(name=name)
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + body + "\n" + text[b:]


def main() -> None:
    m = json.loads((ROOT / "results" / "metrics.json").read_text())
    readme = ROOT / "README.md"
    text = readme.read_text()
    new = fill(fill(text, "headline", headline(m)), "results", results(m))
    if "--check" in sys.argv:
        if new != text:
            print("README is out of date; run python scripts/render_readme.py")
            sys.exit(1)
        print("README matches results/metrics.json")
        return
    readme.write_text(new)
    print("README rendered")


if __name__ == "__main__":
    main()
